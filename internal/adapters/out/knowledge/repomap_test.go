func TestRepoMapFromTheIndex(t *testing.T) {
	ix, root := setup(t)
	ctx := context.Background()
	m, err := ix.RepoMap(ctx, "p", root, nil, nil, 0)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		RepoMapHeader,
		"\n- pay/service.go — PaymentService charges cards. · PaymentService, validate, helper\n",
		"\n- app/cards/CardsScreen.kt · CardsScreen, loadCards\n",
		"\n- README.txt — not code\n",
		"\n- web/cards.ts · CardStore, fetchCards, sumCards\n",
	} {
		if !strings.Contains(m, want) {
			t.Errorf("map misses %q:\n%s", want, m)
		}
	}
	if strings.Contains(m, ".barnraise/") || strings.Contains(m, "node_modules") {
		t.Errorf("Barnraise's documents and skipped folders stay out:\n%s", m)
	}
	again, _ := ix.RepoMap(ctx, "p", root, nil, nil, 0)
	if again != m {
		t.Error("the same files give the same map")
	}

	// An item's worktree: its changed files are read from there.
	wt := t.TempDir()
	writeTree(t, wt, map[string]string{
		"web/cards.ts":   "// Cards of the wallet, fetched and cached.\nexport function fetchCards() {}\nexport function cacheCards() {}\n",
		"web/new.ts":     "export class Fresh {}\n",
		"plan.md":        "# plan\n",
		"rs/lib.rs.tmp":  "x",
		"docs/notes.md":  "---\ntitle: x\n---\n# Notes about payments\n",
		"pay/service.go": "package pay\n",
	})
	os.Remove(filepath.Join(wt, "pay", "service.go"))
	m, err = ix.RepoMap(ctx, "p", wt, []string{"web/cards.ts", "web/new.ts", "plan.md", "pay/service.go", "docs/notes.md", "gone.ts"}, []string{"plan.md"}, 0)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"\n- web/cards.ts — Cards of the wallet, fetched and cached. · fetchCards, cacheCards\n",
		"\n- web/new.ts · Fresh\n",
		"\n- docs/notes.md — Notes about payments\n",
	} {
		if !strings.Contains(m, want) {
			t.Errorf("map misses %q:\n%s", want, m)
		}
	}
	for _, not := range []string{"plan.md", "pay/service.go", "gone.ts"} {
		if strings.Contains(m, not) {
			t.Errorf("%s must be out:\n%s", not, m)
		}
	}

	// Over max_files, the least described files are counted per folder.
	m, _ = ix.RepoMap(ctx, "p", root, nil, nil, 3)
	if strings.Count(m, "\n- ") < 4 || !strings.Contains(m, "## Not listed (over knowledge.map.max_files)") || !strings.Contains(m, "more files\n") {
		t.Errorf("bounded map:\n%s", m)
	}
}

func TestFilePurpose(t *testing.T) {
	cases := map[string]struct{ file, src string }{
		"Package pay charges cards.":                               {"pay/doc.go", "// Copyright 2026 Someone\n// SPDX-License-Identifier: MIT\n\n//go:build linux\n\n// Package pay charges cards.\n// It never stores numbers.\npackage pay\n"},
		"Command tool does a thing over several lines of comment.": {"cmd/tool/main.go", "// Command tool does a thing over several\n// lines of comment.\npackage main\n"},
		"Module docs.":          {"m.py", "#!/usr/bin/env python3\n# -*- coding: utf-8 -*-\n\"\"\"Module docs.\n\nMore.\n\"\"\"\nimport os\n"},
		"Block comment header.": {"a.ts", "/**\n * Block comment header.\n */\nexport const x = 1\n"},
		"Server saves things.":  {"s.go", "package s\n\nimport \"os\"\n\n// Server saves things.\ntype Server struct{}\n"},
		"Deploys the app":       {"deploy.sh", "#!/bin/sh\n# Deploys the app\nset -e\n"},
		"Title":                 {"README.md", "[![badge](x)](y)\n\n# Title\n\ntext\n"},
		"Notes":                 {"docs/n.md", "---\nid: x\n---\n\n## Notes\n"},
		"":                      {"config.yaml", "key: value\n# a comment after code\n"},
	}
	for want, c := range cases {
		if got := filePurpose(c.file, []byte(c.src)); got != want {
			t.Errorf("%s: got %q want %q", c.file, got, want)
		}
	}
	long := "// " + strings.Repeat("word ", 60) + "\npackage x\n"
	if got := filePurpose("x.go", []byte(long)); len(got) > maxPurpose+len("…") || !strings.HasSuffix(got, "…") {
		t.Errorf("long purpose: %q", got)
	}
	if got := filePurpose("g.go", []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\n\npackage g\n")); got != "" {
		t.Errorf("generated header: %q", got)
	}
}

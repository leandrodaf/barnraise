export const lang = /^pt\b/i.test(navigator.language || '') ? 'pt-BR' : 'en';
const dict = lang === 'pt-BR' ? pt : en;

// t returns the text for a key, filling {0}, {1}… with the arguments.
export function t(key, ...args) {
  let s = dict[key];
  if (typeof s !== 'string') s = en[key];
  if (typeof s !== 'string') return key;
  return s.replace(/\{(\d)\}/g, (_, i) => (args[i] === undefined || args[i] === null ? '' : String(args[i])));
}

// tm looks up a value in one of the maps (statuses, events…), falling back to the raw value.
export function tm(map, value) {
  const m = dict[map] || {};
  return m[value] || (en[map] || {})[value] || String(value || '');
}

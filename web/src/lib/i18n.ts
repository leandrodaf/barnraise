import { locale } from './locale.svelte';

// The current language; t() and tm() read it, so the screen follows a switch.
export const getLang = () => locale.lang;
const current = (): Dict => (locale.lang === 'pt-BR' ? pt : en);

// t returns the text for a key, filling {0}, {1}… with the arguments.
export function t(key: string, ...args: unknown[]): string {
  let s = current()[key];
  if (typeof s !== 'string') s = en[key];
  if (typeof s !== 'string') return key;
  return s.replace(/\{(\d)\}/g, (_: string, i: string) => (args[Number(i)] === undefined || args[Number(i)] === null ? '' : String(args[Number(i)])));
}

// tm looks up a value in one of the maps (statuses, events…), falling back to the raw value.
export function tm(map: string, value: unknown): string {
  const m = current()[map] || {};
  const k = String(value ?? '');
  return m[k] || (en[map] || {})[k] || k;
}

package knowledge

import (
	"path"
	"strings"
)

// maxPurpose bounds the purpose of a file in the repository map.
const maxPurpose = 110

// filePurpose is one short line saying what a file is for, read from the
// file itself: the first heading of a Markdown file; for the others the
// comment at the top (package comment, module docstring, header comment)
// or, in code without one, its first doc comment. License headers, build
// tags and tool directives are skipped. A file with none of these has no
// purpose; the map then shows its symbols only.
func filePurpose(rel string, src []byte) string {
	lines := strings.Split(strings.ReplaceAll(string(src[:min(len(src), 16<<10)]), "\r\n", "\n"), "\n")
	if ext := strings.ToLower(path.Ext(rel)); ext == ".md" || ext == ".rst" || ext == ".adoc" || ext == ".txt" {
		return markdownPurpose(lines)
	}
	if p := leadingComment(lines); p != "" {
		return p
	}
	if langOf(rel) != "" {
		return firstDocComment(lines)
	}
	return ""
}

// leadingComment reads the comment before the first line of code.
func leadingComment(lines []string) string {
	for i := 0; i < len(lines) && i < 60; i++ {
		t := strings.TrimSpace(lines[i])
		if t == "" || strings.HasPrefix(t, "#!") || strings.HasPrefix(t, "---") {
			continue
		}
		if !isCommentLine(t) {
			return ""
		}
		if text := commentText(lines, i); text != "" {
			return text
		}
		i = skipComment(lines, i)
	}
	return ""
}

// firstDocComment reads the first comment of at least three words found
// in the top of a file.
func firstDocComment(lines []string) string {
	for i := 0; i < len(lines) && i < 150; i++ {
		t := strings.TrimSpace(lines[i])
		if !isCommentLine(t) {
			continue
		}
		if text := commentText(lines, i); len(strings.Fields(text)) >= 3 {
			return text
		}
		i = skipComment(lines, i)
	}
	return ""
}

func isCommentLine(t string) bool {
	for _, p := range []string{"//", "/*", "*", "#", "--", ";", `"""`, `'''`, "<!--"} {
		if strings.HasPrefix(t, p) && !strings.HasPrefix(t, "#[") && !strings.HasPrefix(t, "#include") && !strings.HasPrefix(t, "#define") {
			return true
		}
	}
	return false
}

// commentText joins the comment that starts at line i until its first
// sentence ends (at most a few lines), skipping directive lines.
func commentText(lines []string, i int) string {
	var parts []string
	for j := i; j < len(lines) && j < i+5; j++ {
		t := strings.TrimSpace(lines[j])
		if t == "" || (j > i && !isCommentLine(t) && !inBlockAt(lines, i, j)) {
			break
		}
		text := stripCommentMarks(t)
		if text == "" {
			if len(parts) > 0 {
				break
			}
			continue
		}
		if directive(text) {
			if len(parts) > 0 {
				break
			}
			continue
		}
		parts = append(parts, text)
		joined := strings.Join(parts, " ")
		if strings.Contains(joined, ". ") || strings.HasSuffix(joined, ".") || strings.HasSuffix(joined, ":") || (j > i && closesBlock(t)) {
			break
		}
	}
	return firstSentence(strings.Join(parts, " "))
}

// inBlockAt: line j is still inside a block comment or docstring opened
// at line i.
func inBlockAt(lines []string, i, j int) bool {
	t := strings.TrimSpace(lines[i])
	rest, ok := "", false
	for _, o := range []string{"/*", `"""`, `'''`, "<!--"} {
		if r, found := strings.CutPrefix(t, o); found {
			rest, ok = r, true
			break
		}
	}
	if !ok || closesBlock(rest) {
		return false
	}
	for k := i + 1; k < j; k++ {
		if closesBlock(lines[k]) {
			return false
		}
	}
	return true
}

// skipComment returns the last line of the comment that starts at i.
func skipComment(lines []string, i int) int {
	j := i
	for j+1 < len(lines) {
		t := strings.TrimSpace(lines[j+1])
		if t == "" || !(isCommentLine(t) || inBlockAt(lines, i, j+1)) {
			break
		}
		j++
	}
	return j
}

func closesBlock(s string) bool {
	return strings.Contains(s, "*/") || strings.Contains(s, `"""`) || strings.Contains(s, `'''`) || strings.Contains(s, "-->")
}

func stripCommentMarks(t string) string {
	for _, p := range []string{"/**", "/*", "///", "//!", "//", "<!--", `"""`, `'''`, "#", "--", ";;", ";", "*"} {
		if strings.HasPrefix(t, p) {
			t = t[len(p):]
			break
		}
	}
	for _, s := range []string{"*/", `"""`, `'''`, "-->"} {
		t = strings.TrimSuffix(strings.TrimSpace(t), s)
	}
	return strings.TrimSpace(strings.TrimLeft(strings.TrimSpace(t), "*#!/ "))
}

// directive: lines that are for tools or lawyers, not for readers.
func directive(text string) bool {
	l := strings.ToLower(text)
	if strings.Contains(l, "do not edit") {
		return true
	}
	for _, p := range []string{"copyright", "spdx-", "license", "licence", "go:build", "+build", "go:generate", "eslint", "prettier", "@ts-",
		"-*-", "nolint", "code generated", "generated by", "@generated", "vim:", "pylint", "noqa", "@flow", "use strict",
		"frozen_string_literal", "#region", "<auto-generated", "syntax=", "type: ignore", "@format"} {
		if strings.HasPrefix(l, p) {
			return true
		}
	}
	return false
}

func markdownPurpose(lines []string) string {
	start := 0
	if len(lines) > 0 && strings.TrimSpace(lines[0]) == "---" {
		for i := 1; i < len(lines) && i < 80; i++ {
			if strings.TrimSpace(lines[i]) == "---" {
				start = i + 1
				break
			}
		}
	}
	for _, ln := range lines[start:] {
		t := strings.TrimSpace(ln)
		if t == "" || strings.HasPrefix(t, "<!--") || strings.HasPrefix(t, "[![") || strings.HasPrefix(t, "![") {
			continue
		}
		return firstSentence(strings.TrimSpace(strings.TrimLeft(t, "#")))
	}
	return ""
}

// firstSentence cuts a text at its first sentence and at maxPurpose bytes.
func firstSentence(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if i := strings.Index(s, ". "); i > 0 {
		s = s[:i+1]
	}
	return oneLine(s, maxPurpose)
}

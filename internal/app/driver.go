func queryChecks(project, itemID string) ports.EventQuery {
	return ports.EventQuery{Project: project, Subject: itemID, Types: []string{domain.EvCheckCompleted}}
}

// WorktreeDir is where an item's worktree lives.
func (s *Service) WorktreeDir(project, itemID string) string {
	return filepath.Join(s.d.DataDir, "worktrees", project, itemID)
}

// ItemPort is the server port of an item's worktree.
func ItemPort(base int, itemID string) int {
	_, n, err := domain.ParseID(itemID)
	if err != nil {
		return base
	}
	return base + n%1000
}

// ensureWorkspace creates the branch, the worktree and the draft PR of an item.
func (s *Service) ensureWorkspace(ctx context.Context, p *Project, itemID string) (string, error) {
	g := p.Ports.Git
	if g == nil {
		return p.Cfg.Root, nil
	}
	p.mu.Lock()
	it := p.state.Items[itemID].Clone()
	p.mu.Unlock()
	dir := s.WorktreeDir(p.Name, itemID)
	if _, err := os.Stat(filepath.Join(dir, ".git")); err == nil {
		return dir, nil
	}
	if err := g.Fetch(ctx); err != nil {
		s.d.Log.Warn("fetch", "err", err)
	}
	main, err := g.MainHead(ctx)
	if err != nil {
		return "", fmt.Errorf("main head: %w", err)
	}
	branch := it.Branch
	if branch == "" {
		branch = domain.BranchName(it.ID, it.Title)
	}
	if err := g.EnsureBranch(ctx, branch, main); err != nil {
		return "", fmt.Errorf("branch %s: %w", branch, err)
	}
	if err := os.MkdirAll(filepath.Dir(dir), 0o755); err != nil {
		return "", err
	}
	if err := g.AddWorktree(ctx, dir, branch); err != nil {
		return "", fmt.Errorf("worktree %s: %w", dir, err)
	}
	// .worktreeinclude: copy local env files the build needs, never commit them.
	for _, f := range p.Cfg.EnvFiles {
		src := filepath.Join(p.Cfg.Root, f)
		if data, err := os.ReadFile(src); err == nil {
			_ = os.WriteFile(filepath.Join(dir, f), data, 0o600)
			s.excludeFromGit(dir, "/"+strings.TrimPrefix(f, "/"))
		}
	}
	if err := s.writeCriteria(dir, it); err != nil {
		return "", err
	}
	s.excludeFromGit(dir, "/.barnraise-session/")
	s.excludeFromGit(dir, "/criteria.json") // regenerated by the daemon; the marks live in the event log
	if p.Ports.CodeHost != nil && it.PR == "" {
		if _, err := g.Head(ctx, dir); err == nil {
			// Push the branch so the PR has a head, then open it as a draft.
			_, _, _ = g.CommitAll(ctx, dir, it.ID+": start\n\n"+domain.CommitTrailer(it.ID))
			_ = g.Push(ctx, dir, branch)
		}
		pr, err := p.Ports.CodeHost.OpenDraftPR(ctx, branch, p.Cfg.MainBranch, prTitle(it), prBody(p, it))
		if err != nil {
			s.d.Log.Warn("open draft PR", "item", itemID, "err", err)
		} else {
			_, _ = s.mutateItem(ctx, p, itemID, domain.EvItemUpdated, "barnraise", func(x *domain.Item) error {
				x.PR = prRef(pr)
				x.Branch = branch
				return nil
			}, domain.Payload{Note: "draft PR " + pr.URL})
		}
	}
	return dir, nil
}

func (s *Service) excludeFromGit(dir, pattern string) {
	// Worktrees share info/exclude through the common dir; a per-worktree
	// exclude goes to the worktree's own git dir.
	gitFile := filepath.Join(dir, ".git")
	data, err := os.ReadFile(gitFile)
	if err != nil {
		return
	}
	gitDir := strings.TrimSpace(strings.TrimPrefix(string(data), "gitdir:"))
	common := gitDir
	if b, err := os.ReadFile(filepath.Join(gitDir, "commondir")); err == nil {
		c := strings.TrimSpace(string(b))
		if !filepath.IsAbs(c) {
			c = filepath.Join(gitDir, c)
		}
		common = c
	}
	ex := filepath.Join(common, "info", "exclude")
	cur, _ := os.ReadFile(ex)
	if strings.Contains(string(cur), "\n"+pattern+"\n") || strings.HasPrefix(string(cur), pattern+"\n") {
		return
	}
	_ = os.MkdirAll(filepath.Dir(ex), 0o755)
	f, err := os.OpenFile(ex, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o644)
	if err != nil {
		return
	}
	defer f.Close()
	if len(cur) > 0 && !strings.HasSuffix(string(cur), "\n") {
		_, _ = f.WriteString("\n")
	}
	_, _ = f.WriteString(pattern + "\n")
}

// writeCriteria writes criteria.json: the analyst writes, the implementer only marks.
func (s *Service) writeCriteria(dir string, it *domain.Item) error {
	data, err := json.MarshalIndent(map[string]any{"item": it.ID, "title": it.Title, "criteria": it.Criteria, "preserve": it.Preserve,
		"note": "Read only. Mark criteria with evidence through `barnraise deliver` or the MCP tool deliver."}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "criteria.json"), append(data, '\n'), 0o644)
}

// commitStep commits and pushes the worktree with the item trailer, after a secret scan.
func (s *Service) commitStep(ctx context.Context, p *Project, itemID, msg string) (string, error) {
	g := p.Ports.Git
	if g == nil {
		return "", nil
	}
	dir := s.WorktreeDir(p.Name, itemID)
	if _, err := os.Stat(dir); err != nil {
		return "", nil
	}
	p.mu.Lock()
	it := p.state.Items[itemID]
	branch := ""
	if it != nil {
		branch = it.Branch
		_ = s.writeCriteria(dir, it)
	}
	p.mu.Unlock()
	if s.d.Exec != nil {
		if found, err := s.scanSecrets(ctx, dir); err != nil {
			return "", err
		} else if found != "" {
			s.notifyOwner(ctx, p, "secret", "Commit blocked: possible secret in "+itemID, found)
			_, _ = s.emit(ctx, p, domain.EvSecretBlocked, itemID, "barnraise", domain.Payload{Note: found})
			return "", fmt.Errorf("commit blocked: possible secret found (%s)", found)
		}
	}
	sha, changed, err := g.CommitAll(ctx, dir, msg+"\n\n"+domain.CommitTrailer(itemID))
	if err != nil {
		return "", err
	}
	if branch != "" {
		if err := g.Push(ctx, dir, branch); err != nil {
			s.d.Log.Warn("push", "item", itemID, "err", err)
		}
	}
	if !changed {
		return sha, nil
	}
	return sha, nil
}

// SecretScanner is set by the composition root (built-in rules or gitleaks).
type SecretScanner func(ctx context.Context, dir string) (string, error)

var secretScanner SecretScanner

// SetSecretScanner installs the scanner used before every push.
func SetSecretScanner(f SecretScanner) { secretScanner = f }

func (s *Service) scanSecrets(ctx context.Context, dir string) (string, error) {
	if secretScanner == nil {
		return "", nil
	}
	return secretScanner(ctx, dir)
}

func prTitle(it *domain.Item) string { return fmt.Sprintf("[%s] %s", it.ID, it.Title) }

func prBody(p *Project, it *domain.Item) string {
	var b strings.Builder
	fmt.Fprintf(&b, "Barnraise item **%s** · kind %s · %s", it.ID, it.Kind, it.Priority)
	if it.GoalID != "" {
		fmt.Fprintf(&b, " · goal %s", it.GoalID)
	}
	if it.Area != "" {
		fmt.Fprintf(&b, " · area %s", it.Area)
	}
	b.WriteString("\n\n")
	if it.TrackerRef != "" {
		fmt.Fprintf(&b, "Tracker: %s\n\n", it.TrackerRef)
	}
	b.WriteString("### Criteria\n")
	b.WriteString(it.CriteriaChecklist())
	if len(it.Preserve) > 0 {
		b.WriteString("\n### What must not change\n- " + strings.Join(it.Preserve, "\n- ") + "\n")
	}
	if len(it.Tweaks) > 0 {
		b.WriteString("\n### Tweaks riding along\n- " + strings.Join(it.Tweaks, "\n- ") + "\n")
	}
	fmt.Fprintf(&b, "\nStep: `%s` · status: `%s`\n", it.Step, it.Status)
	return b.String()
}

func prRef(pr ports.PR) string {
	if pr.URL != "" {
		return fmt.Sprintf("#%d %s", pr.Number, pr.URL)
	}
	return fmt.Sprintf("#%d", pr.Number)
}

func prFromRef(ref string) ports.PR {
	ref = strings.TrimPrefix(ref, "#")
	num, url, _ := strings.Cut(ref, " ")
	n, _ := strconv.Atoi(num)
	return ports.PR{Number: n, URL: url}
}

// driveHeld advances steps of held items that no agent runs: checks,
// owner approvals and scripts. The merge queue runs separately.
func (s *Service) driveHeld(ctx context.Context, p *Project) {
	p.mu.Lock()
	if p.state.Paused {
		p.mu.Unlock()
		return
	}
	type job struct {
		it *domain.Item
		st domain.StepDef
	}
	var jobs []job
	for _, it := range p.state.Items {
		if it.Status != domain.StatusInProgress || it.Claim == nil || it.Claim.Machine != s.d.Machine {
			continue
		}
		if _, busy := p.running[it.ID]; busy {
			continue
		}
		f, err := p.Cfg.FlowFor(it.Kind)
		if err != nil {
			continue
		}
		st, ok := f.Step(it.Step)
		if !ok || stepRole(st) != "" {
			continue
		}
		p.running[it.ID] = "driver"
		jobs = append(jobs, job{it.Clone(), st})
	}
	p.mu.Unlock()
	for _, j := range jobs {
		j := j
		go func() {
			defer s.doneRunning(p, j.it.ID, "driver")
			if err := s.runDriverStep(ctx, p, j.it, j.st); err != nil {
				s.d.Log.Warn("driver step", "item", j.it.ID, "step", j.st.Name, "err", err)
			}
		}()
	}
}

func (s *Service) runDriverStep(ctx context.Context, p *Project, it *domain.Item, st domain.StepDef) error {
	switch st.Type {
	case domain.StepCheck:
		return s.runCheckStep(ctx, p, it, st)
	case domain.StepScript:
		return s.runScriptStep(ctx, p, it, st)
	case domain.StepApproval:
		return s.requestOwnerApproval(ctx, p, it, st)
	case domain.StepMergeQueue:
		_, err := s.mutateItem(ctx, p, it.ID, domain.EvItemQueued, "barnraise", func(x *domain.Item) error {
			x.Status = domain.StatusQueued
			return nil
		}, domain.Payload{})
		return err
	}
	return nil
}

func (s *Service) runCheckStep(ctx context.Context, p *Project, it *domain.Item, st domain.StepDef) error {
	if s.d.Checks == nil {
		return errors.New("no check runner")
	}
	dir, err := s.ensureWorkspace(ctx, p, it.ID)
	if err != nil {
		return err
	}
	names := s.checkNames(p, st)
	head := ""
	main := ""
	touched := it.FilesTouched
	if p.Ports.Git != nil {
		head, _ = p.Ports.Git.Head(ctx, dir)
		main, _ = p.Ports.Git.MainHead(ctx)
		if main != "" && head != "" {
			if files, err := s.itemFiles(ctx, p, main, head); err == nil {
				touched = domain.Dedupe(append(touched, files...))
			}
		}
	}
	// Existing tests and check scripts are locked: an item that changed one fails.
	if locked := s.lockedChanges(ctx, p, main, touched); len(locked) > 0 {
		_, _, err := s.finishStep(ctx, p, stepOutcome{Item: it.ID, Step: st.Name, Outcome: domain.OutcomeFail, Actor: "checks",
			Reason: "existing tests, references or check scripts were changed (they are locked; add new tests instead): " + strings.Join(locked, ", ")})
		return err
	}
	areas := map[string]bool{}
	for _, f := range touched {
		if a := p.Cfg.AreaOfFile(f); a != "" {
			areas[a] = true
		}
	}
	var areaList []string
	for a := range areas {
		areaList = append(areaList, a)
	}
	if st.Require == "failing_test_now_passes" {
		if ok, reason := s.reproductionHolds(ctx, p, it, names); !ok {
			_, _, err := s.finishStep(ctx, p, stepOutcome{Item: it.ID, Step: st.Name, Outcome: domain.OutcomeFail, Reason: reason, Actor: "checks"})
			return err
		}
	}
	// Every criterion needs a check that verifies it.
	if missing := domain.CriteriaCoverage(it, func(c string) bool { return c != "" }); len(missing) > 0 {
		_, _, err := s.finishStep(ctx, p, stepOutcome{Item: it.ID, Step: st.Name, Outcome: domain.OutcomeFail, Actor: "checks",
			Reason: "criteria without a check: " + strings.Join(missing, ", ")})
		return err
	}
	pendingAny := false
	for _, n := range names {
		def, ok := p.Cfg.Checks[n]
		if !ok {
			continue
		}
		if st.Scope != "" {
			def.Scope = st.Scope
		}
		_, _ = s.emit(ctx, p, domain.EvCheckRequested, it.ID, "barnraise", domain.Payload{Note: n, Extra: map[string]any{"check": n, "runs_on": def.RunsOn, "commit": head}})
		spec := ports.CheckSpec{Def: def, ItemID: it.ID, Branch: it.Branch, Commit: head, Dir: dir, Touched: touched, Areas: areaList,
			Env: map[string]string{"PORT": strconv.Itoa(ItemPort(p.Cfg.PortBase, it.ID))}}
		res, pending, err := s.d.Checks.Run(ctx, spec)
		if err != nil {
			res = domain.CheckResult{Check: n, Passed: false, Summary: "check could not run: " + err.Error()}
		}
		if pending {
			pendingAny = true
			continue
		}
		res.ItemID, res.Check, res.Commit = it.ID, n, head
		if res.ID == "" {
			res.ID = s.d.IDs.NewID()
		}
		res.At = s.d.Clock.Now().UTC()
		if _, err := s.emit(ctx, p, domain.EvCheckCompleted, it.ID, "checks", domain.Payload{Check: &res}); err != nil {
			return err
		}
		if p.Ports.CodeHost != nil && head != "" {
			go func(n string, r domain.CheckResult, pr string) {
				_ = p.Ports.CodeHost.ReportCheck(context.Background(), head, n, r.Passed, truncate(r.Summary, 140))
				// Preview: prints, flow video, APK or preview link from the check go to the PR.
				if len(r.Artifacts) > 0 && pr != "" {
					_ = p.Ports.CodeHost.Comment(context.Background(), prFromRef(pr), "**Preview from check "+n+"**\n- "+strings.Join(r.Artifacts, "\n- "))
				}
			}(n, res, it.PR)
		}
	}
	if pendingAny {
		return nil // results come through ReportCheck
	}
	results := s.checkResultsSince(ctx, p, it.ID, it.StepStartedAt)
	passed, reason, complete := aggregateChecks(names, results)
	if !complete {
		return nil
	}
	outcome := domain.OutcomePass
	if !passed {
		outcome = domain.OutcomeFail
	}
	_, _, err = s.finishStep(ctx, p, stepOutcome{Item: it.ID, Step: st.Name, Outcome: outcome, Reason: reason, Actor: "checks"})
	return err
}

// itemFiles are the files the item changed since it forked from main
// (three-dot), without the item's own memory files.
func (s *Service) itemFiles(ctx context.Context, p *Project, main, head string) ([]string, error) {
	base, err := p.Ports.Git.MergeBase(ctx, main, head)
	if err != nil {
		base = main
	}
	files, err := p.Ports.Git.ChangedFiles(ctx, base, head)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, f := range files {
		if !domain.Contains(ItemFiles, f) {
			out = append(out, f)
		}
	}
	return out, nil
}

// lockedChanges returns touched files that are locked because they existed on main.
func (s *Service) lockedChanges(ctx context.Context, p *Project, main string, touched []string) []string {
	if p.Ports.Git == nil || main == "" {
		return nil
	}
	var out []string
	for _, f := range touched {
		for _, g := range p.Cfg.Policy.LockExisting {
			if domain.MatchGlob(g, f) && p.Ports.Git.ExistsAt(ctx, main, f) {
				out = append(out, f)
				break
			}
		}
	}
	return out
}

// reproductionHolds checks the bug's reproduction test fails on main.
func (s *Service) reproductionHolds(ctx context.Context, p *Project, it *domain.Item, names []string) (bool, string) {
	g := p.Ports.Git
	if g == nil || s.d.Checks == nil || len(names) == 0 {
		return true, ""
	}
	files := s.reproductionFiles(ctx, p, it.ID)
	if len(files) == 0 {
		return false, "no reproduction test was delivered in the reproduce step"
	}
	main, err := g.MainHead(ctx)
	if err != nil {
		return true, ""
	}
	tmp := filepath.Join(s.d.DataDir, "repro", p.Name, it.ID+"-"+short(s.d.IDs.NewID()))
	if err := g.AddDetachedWorktree(ctx, tmp, main); err != nil {
		return true, ""
	}
	defer func() { _ = g.RemoveWorktree(ctx, tmp) }()
	src := s.WorktreeDir(p.Name, it.ID)
	for _, f := range files {
		data, err := os.ReadFile(filepath.Join(src, f))
		if err != nil {
			continue
		}
		_ = os.MkdirAll(filepath.Dir(filepath.Join(tmp, f)), 0o755)
		_ = os.WriteFile(filepath.Join(tmp, f), data, 0o644)
	}
	def := p.Cfg.Checks[names[0]]
	def.FlakyRetries = 1
	def.Scope = "all"
	res, pending, err := s.d.Checks.Run(ctx, ports.CheckSpec{Def: def, ItemID: it.ID, Dir: tmp, Main: true})
	if err != nil || pending {
		return true, ""
	}
	if res.Passed {
		return false, "the reproduction test passes on main, so it does not reproduce the bug: " + strings.Join(files, ", ")
	}
	return true, ""
}

// reproductionFiles are the files delivered by the reproduce step.
func (s *Service) reproductionFiles(ctx context.Context, p *Project, itemID string) []string {
	evs, err := s.d.Store.Query(ctx, ports.EventQuery{Project: p.Name, Subject: itemID, Types: []string{domain.EvDeliverySubmitted}})
	if err != nil {
		return nil
	}
	f, err := p.Cfg.FlowFor(p.Snapshot().Items[itemID].Kind)
	if err != nil {
		return nil
	}
	var files []string
	for _, e := range evs {
		pl, _ := e.DecodePayload()
		if pl.Delivery == nil {
			continue
		}
		if st, ok := f.Step(pl.Delivery.Step); ok && st.Output == "failing_test" {
			files = pl.Delivery.Files
		}
	}
	return files
}

func (s *Service) runScriptStep(ctx context.Context, p *Project, it *domain.Item, st domain.StepDef) error {
	if s.d.Exec == nil {
		return errors.New("no exec")
	}
	dir, err := s.ensureWorkspace(ctx, p, it.ID)
	if err != nil {
		return err
	}
	res, err := s.d.Exec.Run(ctx, ports.Cmd{Name: "sh", Args: []string{"-c", st.Run}, Dir: dir, Timeout: 30 * time.Minute,
		Env: append(os.Environ(), "BARNRAISE_ITEM="+it.ID, "BARNRAISE_STEP="+st.Name)})
	outcome := domain.OutcomePass
	reason := ""
	if err != nil || res.ExitCode != 0 {
		outcome = domain.OutcomeFail
		out := string(res.Stdout) + string(res.Stderr)
		if err != nil {
			out += err.Error()
		}
		reason = "script failed: " + tail(out, 2000)
	}
	_, _, err = s.finishStep(ctx, p, stepOutcome{Item: it.ID, Step: st.Name, Outcome: outcome, Reason: reason, Actor: "script"})
	return err
}

func tail(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return "…" + s[len(s)-n:]
}

// requestOwnerApproval asks the owner, once, to approve the plan or the delivery.
func (s *Service) requestOwnerApproval(ctx context.Context, p *Project, it *domain.Item, st domain.StepDef) error {
	what := approvalWhat(p, it, st)
	p.mu.Lock()
	defer p.mu.Unlock()
	cur := p.state.Items[it.ID]
	if cur == nil || cur.WaitingQuestion != "" || cur.Step != st.Name {
		return nil
	}
	q := &domain.Question{ItemID: it.ID, Context: fmt.Sprintf("%s (%s) is at step %s.", it.ID, it.Title, st.Name),
		Decision: fmt.Sprintf("Approve the %s of %s?", what, it.ID),
		Options:  []domain.Option{{Label: "Approve the " + what, Recommended: true}, {Label: "Send back for rework"}},
		IfNoAnswer: "The item waits; agents work on other items.", Urgent: true}
	qid, err := s.askLocked(ctx, p, q, "barnraise")
	if err != nil {
		return err
	}
	_, err = s.mutateItemLocked(ctx, p, it.ID, domain.EvItemWaitingOwner, "barnraise", func(x *domain.Item) error {
		x.Status = domain.StatusWaitingOwner
		x.WaitingQuestion = qid
		return nil
	}, domain.Payload{Note: "waiting for the owner to approve the " + what})
	if err == nil {
		go s.notifyOwner(context.Background(), p, "owner_approval", q.Decision, it.Title)
	}
	return err
}

// approvalWhat names what an approval step approves: plan, delivery or post.
func approvalWhat(p *Project, it *domain.Item, st domain.StepDef) string {
	f, err := p.Cfg.FlowFor(it.Kind)
	if err != nil {
		return "delivery"
	}
	idx := f.Index(st.Name)
	for i := idx - 1; i >= 0; i-- {
		prev := f.Steps[i]
		if prev.Type == domain.StepAgent && !prev.Review {
			if prev.Output == "plan.md" {
				return "plan"
			}
			return "delivery"
		}
	}
	return "delivery"
}
